package com.gentech.starter_kit

import io.flutter.embedding.engine.plugins.FlutterPlugin

/**
 * Intentional placeholder plugin.
 *
 * The starter kit currently has no native (Kotlin) code — all functionality is
 * Dart/Flutter. This empty [FlutterPlugin] only exists so the package is
 * registered as a plugin, reserving the entry point for future native code.
 * It does nothing by design; do not mistake it for dead code.
 */
class StarterKitPlugin: FlutterPlugin {
    override fun onAttachedToEngine(binding: FlutterPlugin.FlutterPluginBinding) {}
    override fun onDetachedFromEngine(binding: FlutterPlugin.FlutterPluginBinding) {}
}
